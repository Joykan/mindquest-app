from svgkit import *
s=Svg(640,1000)
def term(cx,cy,t,w=110):
    s.box(cx-w/2,cy-18,w,36,t,13,fill=MINT,stroke=FOREST,rx=18,bold=True)
def io(cx,cy,w,h,t):
    k=16
    s.parts.append(f'<polygon points="{cx-w/2+k},{cy-h/2} {cx+w/2+k},{cy-h/2} {cx+w/2-k},{cy+h/2} {cx-w/2-k},{cy+h/2}" fill="#EEF4FB" stroke="#3B6EA5" stroke-width="1.6"/>')
    s.parts+=s._text_lines(cx,cy,t.split('\n'),12)
def diamond(cx,cy,w,h,t):
    s.parts.append(f'<polygon points="{cx},{cy-h/2} {cx+w/2},{cy} {cx},{cy+h/2} {cx-w/2},{cy}" fill="#FFF7E6" stroke="#B7862B" stroke-width="1.6"/>')
    s.parts+=s._text_lines(cx,cy,t.split('\n'),12)
def proc(cx,cy,w,h,t,fill='white',stroke=GREEN):
    s.box(cx-w/2,cy-h/2,w,h,t,12,fill=fill,stroke=stroke,rx=0)
